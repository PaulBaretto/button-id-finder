  function saveRecord(rec) {
    const item = { ...rec, savedAt: new Date().toISOString() };
    try {
      chrome.storage.local.get({ bif_saved: [] }, (res) => {
        const list = (res.bif_saved || []).filter((r) => !(r.page === item.page && r.bestValue === item.bestValue));
        list.push(item);
        chrome.storage.local.set({ bif_saved: list }, () => toast(`Saved · ${list.length} item${list.length === 1 ? '' : 's'} in your list`));
      });
    } catch (e) {
      toast('Could not save — reload the page and try again');
    }
  }

